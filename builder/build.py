#!/usr/bin/env python3
"""
Bundle `src/` into a single self-contained file: `dist/anti-custheme.bundle.js`.

The CSS from `src/styles/` is embedded as a string and injected as a <style> element at startup,
so the patched app only has to execute one file. Modules are plain IIFEs that attach to
`window.AntiCusTheme`; JS_MODULE_ORDER is their dependency order.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import List

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = PROJECT_ROOT / "src"
DIST_DIR = PROJECT_ROOT / "dist"
BUNDLE_NAME = "anti-custheme.bundle.js"

JS_MODULE_ORDER: List[str] = [
    "core/constants.js",
    "palettes/themes-palette.js",
    "core/state.js",
    "wallpapers/scenes-nature.js",
    "wallpapers/scenes-night.js",
    "wallpapers/scenes-unicorn.js",
    "wallpapers/engine.js",
    "core/dom-adapter.js",
    "core/fonts.js",
    "components/mascot.js",
    "components/theme-picker.js",
    "components/slash-command.js",
    "index.js",
]

CSS_MODULE_ORDER: List[str] = [
    "styles/theme.css",
]

STYLE_LOADER = """
  window.AntiCusTheme = window.AntiCusTheme || {};
  window.AntiCusTheme.EMBEDDED_CSS = %s;
  (function ensureStyles() {
    if (!document.head) {
      window.addEventListener('DOMContentLoaded', ensureStyles, { once: true });
      return;
    }
    if (document.getElementById('act-css')) return;
    var styleEl = document.createElement('style');
    styleEl.id = 'act-css';
    styleEl.textContent = window.AntiCusTheme.EMBEDDED_CSS;
    document.head.appendChild(styleEl);
  })();
"""


def _read(rel: str) -> str:
    path = SRC_DIR / rel
    if not path.exists():
        raise FileNotFoundError(f"Missing source module: {path}")
    return path.read_text(encoding="utf-8")


def build_bundle() -> Path:
    DIST_DIR.mkdir(parents=True, exist_ok=True)
    css = "\n\n".join(f"/* --- {rel} --- */\n{_read(rel)}" for rel in CSS_MODULE_ORDER)

    parts = [
        "/* anti_cusTheme for Antigravity - generated by builder/build.py, edit src/ instead. */",
        "(function () {",
        "  'use strict';",
        "  if (typeof window === 'undefined' || typeof document === 'undefined') return;",
        STYLE_LOADER % json.dumps(css),
    ]
    for rel in JS_MODULE_ORDER:
        parts.append(f"\n  /* ==================== {rel} ==================== */")
        parts.append(_read(rel))
    parts.append("})();\n")

    out = DIST_DIR / BUNDLE_NAME
    out.write_text("\n".join(parts), encoding="utf-8")
    return out


if __name__ == "__main__":
    path = build_bundle()
    print(f"[build] {path} ({path.stat().st_size:,} bytes)")
